import os
import json
import math
import re
import urllib.request
import urllib.error
from typing import List, Dict, Any, Optional
from ..models.evaluation_model import (
    EvaluationRequest, EvaluationResponse, QuestionEvaluationResult,
    ConceptMatchResult, QuestionRubric, StudentAnswerItem, KeyConceptRubric
)
from ..utils.text_utils import tokenize, calculate_jaccard_similarity
from .feedback_service import FeedbackService

class EvaluationService:
    """
    AI-Assisted Answer Evaluation Service.
    
    Architecture & Flow:
    1. Question + Model Answer + Student Answer + Evaluation Rubric
    2. AI Evaluation (Gemini multimodal semantic evaluator with resilient NLP & rubric fallback)
    3. Suggested Marks + Feedback + Confidence
    
    CRITICAL POLICY:
    All results emitted by this service are explicitly classified as AI SUGGESTIONS (is_suggestion=True,
    status='PENDING_TEACHER_REVIEW'). The institutional Java backend stores these suggestions,
    allowing faculty educators to inspect, adjust, or override individual marks before final grades are assigned.
    """

    @staticmethod
    def evaluate_submission(request: EvaluationRequest) -> EvaluationResponse:
        """
        Executes AI evaluation across all questions in an examination submission.
        Combines rubric-based conceptual mapping, semantic similarity, and AI synthesis
        to output suggested marks, feedback, and confidence scores.
        """
        question_evals: List[QuestionEvaluationResult] = []
        total_suggested = 0.0
        total_possible = 0.0
        confidence_accum = 0.0

        for q in request.questions:
            student_item = next(
                (sa for sa in request.student_answers if sa.question_number == q.question_number),
                None
            )
            student_text = student_item.student_answer_text if student_item else ""
            
            # Execute per-question AI evaluation flow
            q_result = EvaluationService.evaluate_single_question(
                question_number=q.question_number,
                question_text=q.question_text,
                model_answer=q.model_answer,
                student_answer=student_text,
                max_marks=q.max_marks,
                key_concepts=q.key_concepts or [],
                leniency_threshold_pct=q.leniency_threshold_pct or 80.0
            )

            question_evals.append(q_result)
            total_suggested += q_result.suggested_marks
            total_possible += q_result.max_marks
            confidence_accum += q_result.confidence

        q_count = max(1, len(question_evals))
        avg_confidence = round(confidence_accum / q_count, 2)
        percentage = round((total_suggested / max(1.0, total_possible)) * 100.0, 1)
        grade = FeedbackService.calculate_letter_grade(percentage)
        overall = FeedbackService.generate_overall_summary(
            request.student_name or "Candidate",
            percentage,
            grade,
            question_evals
        )

        return EvaluationResponse(
            student_name=request.student_name or "Candidate",
            suggested_total_marks=round(total_suggested, 1),
            total_score=round(total_suggested, 1),
            max_score=round(total_possible, 1),
            percentage=percentage,
            grade=grade,
            confidence=avg_confidence,
            is_suggestion=True,
            status="PENDING_TEACHER_REVIEW",
            disclaimer="This evaluation is generated by AI as a recommendation. Final marks must be reviewed and finalized by the instructor.",
            question_evaluations=question_evals,
            overall_summary=overall["summary"],
            key_strengths=overall["strengths"],
            priority_improvements=overall["improvements"],
            blooms_taxonomy_level=overall["blooms_level"]
        )

    @staticmethod
    def evaluate_single_question(
        question_number: int,
        question_text: str,
        model_answer: str,
        student_answer: str,
        max_marks: float,
        key_concepts: List[KeyConceptRubric],
        leniency_threshold_pct: float = 80.0
    ) -> QuestionEvaluationResult:
        """
        Evaluates a single question following the strict pipeline:
        Question + Model Answer + Student Answer + Evaluation Rubric
        -> AI Evaluation
        -> Suggested Marks + Feedback + Confidence
        """
        # Step 1: Attempt Gemini GenAI semantic evaluation if API key is present
        gemini_result = EvaluationService._try_gemini_evaluation(
            question_number=question_number,
            question_text=question_text,
            model_answer=model_answer,
            student_answer=student_answer,
            max_marks=max_marks,
            key_concepts=key_concepts
        )

        if gemini_result is not None:
            return gemini_result

        # Step 2: High-fidelity Deterministic Semantic & Rubric Engine (Zero-dependency Fallback)
        return EvaluationService._evaluate_with_rubric_engine(
            question_number=question_number,
            question_text=question_text,
            model_answer=model_answer,
            student_answer=student_answer,
            max_marks=max_marks,
            key_concepts=key_concepts,
            leniency_threshold_pct=leniency_threshold_pct
        )

    @staticmethod
    def _evaluate_with_rubric_engine(
        question_number: int,
        question_text: str,
        model_answer: str,
        student_answer: str,
        max_marks: float,
        key_concepts: List[KeyConceptRubric],
        leniency_threshold_pct: float = 80.0
    ) -> QuestionEvaluationResult:
        """
        Semantic NLP engine evaluating token overlap, semantic coverage,
        rubric concept presence, and synonym variations.
        """
        student_text_clean = student_answer.strip()
        model_text_clean = model_answer.strip()

        # Check for empty submission
        if not student_text_clean:
            return QuestionEvaluationResult(
                question_number=question_number,
                question_text=question_text,
                student_answer_text="",
                model_answer_text=model_text_clean,
                max_marks=max_marks,
                suggested_marks=0.0,
                awarded_marks=0.0,
                semantic_similarity_score=0.0,
                concept_matches=[
                    ConceptMatchResult(
                        concept=c.concept,
                        awarded_marks=0.0,
                        max_marks=c.weight_marks,
                        matched_phrases=[],
                        is_satisfied=False
                    ) for c in key_concepts
                ],
                feedback=f"No answer provided for Question {question_number}.",
                strengths=[],
                improvements=["Provide a substantive response addressing the question."],
                confidence=0.99,
                confidence_score=0.99,
                is_suggestion=True
            )

        student_tokens = tokenize(student_text_clean)
        model_tokens = tokenize(model_text_clean)

        # 1. Word overlap and token coverage
        similarity = calculate_jaccard_similarity(student_tokens, model_tokens)
        matched_model_tokens = [t for t in model_tokens if t in student_tokens]
        coverage = len(matched_model_tokens) / max(1, len(model_tokens))
        
        # Calculate semantic score [0.0 - 100.0]
        semantic_score = min(100.0, round((similarity * 0.35 + coverage * 0.65) * 100.0, 1))

        # 2. Key concept rubric evaluation
        concept_matches: List[ConceptMatchResult] = []
        concept_marks_total = 0.0
        satisfied_count = 0

        for c in key_concepts:
            c_tokens = tokenize(c.concept)
            c_lower = c.concept.lower()
            student_lower = student_text_clean.lower()

            # Exact phrase match or token match or synonym match
            phrase_match = c_lower in student_lower
            token_matches = [t for t in c_tokens if t in student_tokens]
            token_satisfied = len(token_matches) >= max(1, math.ceil(len(c_tokens) * 0.6))
            synonym_matched = any(syn.lower() in student_lower for syn in c.synonyms)

            is_satisfied = phrase_match or token_satisfied or synonym_matched
            matched_phrases = []
            if phrase_match:
                matched_phrases.append(c.concept)
            matched_phrases.extend(token_matches)
            for syn in c.synonyms:
                if syn.lower() in student_lower:
                    matched_phrases.append(syn)

            awarded = c.weight_marks if is_satisfied else 0.0
            concept_marks_total += awarded
            if is_satisfied:
                satisfied_count += 1

            concept_matches.append(
                ConceptMatchResult(
                    concept=c.concept,
                    awarded_marks=round(awarded, 1),
                    max_marks=c.weight_marks,
                    matched_phrases=list(set(matched_phrases)),
                    is_satisfied=is_satisfied
                )
            )

        # 3. Suggested Marks Calculation
        if key_concepts:
            total_rubric_weight = sum(c.weight_marks for c in key_concepts)
            if total_rubric_weight > 0:
                # Scale concept marks proportionally to max_marks if needed
                scaling_ratio = max_marks / total_rubric_weight
                suggested_marks = min(max_marks, round(concept_marks_total * scaling_ratio, 1))
            else:
                suggested_marks = round((semantic_score / 100.0) * max_marks, 1)
        else:
            suggested_marks = round((semantic_score / 100.0) * max_marks, 1)

        # Leniency threshold safeguard
        if semantic_score >= leniency_threshold_pct:
            suggested_marks = max(suggested_marks, round(max_marks * 0.9, 1))

        # Clamp suggested marks strictly to [0, max_marks]
        suggested_marks = max(0.0, min(max_marks, suggested_marks))

        # 4. Confidence Score Calculation
        # Confidence reflects semantic alignment clarity and answer length
        word_count = len(student_text_clean.split())
        base_confidence = 0.92
        if word_count >= 15:
            base_confidence += 0.03
        elif word_count < 6:
            base_confidence -= 0.05

        if key_concepts:
            rubric_ratio = satisfied_count / max(1, len(key_concepts))
            if rubric_ratio > 0.8 or rubric_ratio < 0.2:
                base_confidence += 0.03  # Clear consensus
            else:
                base_confidence -= 0.02  # Borderline evaluation

        confidence = round(max(0.70, min(0.98, base_confidence)), 2)

        # 5. Feedback Generation
        analysis = FeedbackService.generate_question_feedback(
            question_number,
            semantic_score,
            concept_matches,
            max_marks,
            suggested_marks
        )

        return QuestionEvaluationResult(
            question_number=question_number,
            question_text=question_text,
            student_answer_text=student_text_clean,
            model_answer_text=model_text_clean,
            max_marks=max_marks,
            suggested_marks=suggested_marks,
            awarded_marks=suggested_marks,
            semantic_similarity_score=semantic_score,
            concept_matches=concept_matches,
            feedback=analysis["feedback"],
            strengths=analysis["strengths"],
            improvements=analysis["improvements"],
            confidence=confidence,
            confidence_score=confidence,
            is_suggestion=True
        )

    @staticmethod
    def _try_gemini_evaluation(
        question_number: int,
        question_text: str,
        model_answer: str,
        student_answer: str,
        max_marks: float,
        key_concepts: List[KeyConceptRubric]
    ) -> Optional[QuestionEvaluationResult]:
        """
        Calls Gemini API with Question + Model Answer + Student Answer + Rubric
        to produce AI-assisted evaluation, suggested marks, feedback, and confidence.
        Returns None on any error or missing credentials to trigger graceful fallback.
        """
        api_key = os.environ.get("GEMINI_API_KEY")
        if not api_key:
            return None

        # Prepare rubric description
        rubric_items_str = "\n".join([
            f"- Concept: '{c.concept}' (Weight: {c.weight_marks} marks, Synonyms: {', '.join(c.synonyms)})"
            for c in key_concepts
        ]) or "No explicit rubric concepts provided. Grade based on model answer coverage."

        prompt = f"""You are an expert university academic grading assistant.
Evaluate the student's answer against the model answer and evaluation rubric.
Remember: Your result is an AI SUGGESTION for faculty review.

[QUESTION {question_number}]
Question: {question_text}
Max Marks: {max_marks}

[BENCHMARK MODEL ANSWER]
{model_answer}

[EVALUATION RUBRIC]
{rubric_items_str}

[STUDENT ANSWER]
{student_answer}

Provide a rigorous evaluation in valid JSON with these exact keys:
{{
  "suggested_marks": <number between 0 and {max_marks}>,
  "confidence": <number between 0.0 and 1.0>,
  "semantic_similarity_score": <number between 0 and 100>,
  "feedback": "<concise constructive formative feedback for student and teacher>",
  "strengths": ["<strength 1>", "<strength 2>"],
  "improvements": ["<improvement 1>", "<improvement 2>"],
  "concept_evaluations": [
    {{
      "concept": "<concept text>",
      "awarded_marks": <number>,
      "is_satisfied": <boolean>,
      "matched_phrases": ["<phrase>"]
    }}
  ]
}}
Only return the JSON object, no markdown or additional text."""

        try:
            url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key={api_key}"
            payload = {
                "contents": [{"parts": [{"text": prompt}]}],
                "generationConfig": {
                    "temperature": 0.1,
                    "responseMimeType": "application/json"
                }
            }
            data = json.dumps(payload).encode("utf-8")
            req = urllib.request.Request(
                url,
                data=data,
                headers={"Content-Type": "application/json"},
                method="POST"
            )

            with urllib.request.urlopen(req, timeout=12) as response:
                if response.status == 200:
                    resp_body = response.read().decode("utf-8")
                    parsed = json.loads(resp_body)
                    candidates = parsed.get("candidates", [])
                    if candidates:
                        text = candidates[0].get("content", {}).get("parts", [{}])[0].get("text", "")
                        eval_json = json.loads(text)
                        
                        suggested_marks = float(eval_json.get("suggested_marks", max_marks * 0.8))
                        suggested_marks = max(0.0, min(max_marks, round(suggested_marks, 1)))
                        confidence = float(eval_json.get("confidence", 0.95))
                        confidence = max(0.5, min(1.0, round(confidence, 2)))
                        similarity = float(eval_json.get("semantic_similarity_score", 85.0))

                        concept_matches = []
                        for ce in eval_json.get("concept_evaluations", []):
                            matching_rubric = next((c for c in key_concepts if c.concept.lower() == ce.get("concept", "").lower()), None)
                            max_m = matching_rubric.weight_marks if matching_rubric else (max_marks / max(1, len(key_concepts)))
                            concept_matches.append(
                                ConceptMatchResult(
                                    concept=ce.get("concept", "Core Concept"),
                                    awarded_marks=float(ce.get("awarded_marks", 0.0)),
                                    max_marks=max_m,
                                    matched_phrases=ce.get("matched_phrases", []),
                                    is_satisfied=bool(ce.get("is_satisfied", False))
                                )
                            )

                        return QuestionEvaluationResult(
                            question_number=question_number,
                            question_text=question_text,
                            student_answer_text=student_answer,
                            model_answer_text=model_answer,
                            max_marks=max_marks,
                            suggested_marks=suggested_marks,
                            awarded_marks=suggested_marks,
                            semantic_similarity_score=similarity,
                            concept_matches=concept_matches,
                            feedback=eval_json.get("feedback", "Evaluation completed against benchmark rubric."),
                            strengths=eval_json.get("strengths", ["Solid conceptual alignment"]),
                            improvements=eval_json.get("improvements", ["Expand on technical details"]),
                            confidence=confidence,
                            confidence_score=confidence,
                            is_suggestion=True
                        )
        except Exception:
            # Fall back seamlessly to local deterministic engine
            return None

        return None
